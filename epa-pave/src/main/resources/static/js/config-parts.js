// Small pieces the views of the Config tab share, so that one fact is drawn one way on all of them.

import {el, code, token} from './dom.js';
import {formProblem, markFieldErrors} from './forms.js';
import {errorPanel} from './result.js';

/** The kind of an environment, drawn the way the frame and the colour key draw it. */
export function kindMark(kind) {
    return el('span', {class: 'kind kind--' + token(kind)}, kind);
}

/** An environment by name with its kind, or the words for none. */
export function environmentName(environment) {
    return environment && environment.active
        ? [el('strong', null, environment.name), ' ', kindMark(environment.kind)]
        : none('none active');
}

/** Words in the place of something that is not there. Never a blank cell. */
export function none(text, title) {
    return el('span', {class: 'presence presence--none', title}, text);
}

/** A short mark in words: a script, a write, a correction made by hand. */
export function flag(text, title) {
    return el('span', {class: 'flag', title}, text);
}

/** The server's sentences, each as it was sent, one to a line. Nothing for an empty list. */
export function sentences(list, extraClass) {
    if (!list || list.length === 0) {
        return null;
    }
    return el('ul', {class: 'note-list' + (extraClass ? ' ' + extraClass : '')}, list.map(text => el('li', null, text)));
}

/** A placeholder the way it is written in a url, a header or a body. */
export function placeholder(name) {
    return code('{{' + name + '}}');
}

// Where the value of a placeholder came from. The server sends the layer by name and has no
// sentence for it, so the words are here. A layer this page does not know is shown under its own name.
const SOURCES = {
    RUN_VALUE: 'typed for this try',
    ENVIRONMENT: 'the active environment',
    COLLECTION: 'a variable of the collection',
    APPLICATION_YML: 'application.yml',
    GENERATED: 'generated by this tool',
    OPERATING_SYSTEM: 'the operating system',
    UNRESOLVED: 'nowhere: it has no value'
};

export function sourceWords(source) {
    return Object.prototype.hasOwnProperty.call(SOURCES, source) ? SOURCES[source] : code(String(source));
}

/**
 * What goes on screen for an answer that is not a completed call. A form problem is marked at the
 * fields it names, inside roots, and what it could not place is listed. Anything else is the
 * server's sentence in the error panel.
 */
export function refusal(answer, roots) {
    if (answer.kind === 'form') {
        return formProblem(answer.body, markFieldErrors(roots || [], answer.body.fieldErrors));
    }
    return errorPanel(answer.body);
}

/**
 * Runs one action from a control. Meanwhile the control is marked busy and cannot be used again,
 * so a second press does not send a second change. The control comes back whatever happened.
 */
export async function during(control, action) {
    if (control.disabled) {
        return undefined;
    }
    control.disabled = true;
    control.setAttribute('aria-busy', 'true');
    try {
        return await action();
    } finally {
        control.disabled = false;
        control.setAttribute('aria-busy', 'false');
    }
}

/** A count with its noun, singular or plural. */
export function counted(value, one, many) {
    return value.toLocaleString() + ' ' + (value === 1 ? one : many);
}

/** A request of a collection by name, with the folders it sits in when it sits in any. */
export function requestName(request) {
    const folders = request.folderPath || [];
    return [el('strong', null, request.name),
        folders.length > 0 ? el('div', {class: 'small quiet'}, 'in ', folders.join(' / ')) : null];
}

/** The marks a request of a collection carries: what a tester should know before using it. */
export function requestMarks(request) {
    const marks = [];
    if (request.scripted) {
        marks.push(flag('pre-request script', 'Postman would run a script before this request. This tool never runs it, so a value the script would have set is not set.'));
    }
    if (request.testScripted) {
        marks.push(flag('script after the response', 'Postman would run a script after the response, which may store a value a later request needs. This tool never runs it.'));
    }
    if (request.guardedAsWrite) {
        marks.push(flag('counts as a write', 'Sending this request as the operation it is mapped to counts as a write. On a production environment it needs writes to be unlocked. '
            + 'Sent as written, a request is judged again by its method, name, url and headers.'));
    }
    if (request.detectionConflict) {
        marks.push(flag('name and url disagree', 'The name reads as one operation and the url as another. The name was followed.'));
    }
    return marks.length > 0 ? el('div', {class: 'config-marks'}, marks) : null;
}
